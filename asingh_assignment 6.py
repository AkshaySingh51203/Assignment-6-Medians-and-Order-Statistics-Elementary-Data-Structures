class Stack:

    def __init__(self):

        self.items=[]


    def push(self,value):

        self.items.append(value)


    def pop(self):

        if self.items:

            return self.items.pop()


    def peek(self):

        return self.items[-1]


    def display(self):

        return self.items



# -----------------------------
# Queue Implementation
# -----------------------------

class Queue:

    def __init__(self):

        self.items=[]


    def enqueue(self,value):

        self.items.append(value)


    def dequeue(self):

        if self.items:

            return self.items.pop(0)


    def display(self):

        return self.items



# -----------------------------
# Linked List Implementation
# -----------------------------

class Node:

    def __init__(self,value):

        self.value=value

        self.next=None



class LinkedList:

    def __init__(self):

        self.head=None



    def insert(self,value):

        new_node=Node(value)

        new_node.next=self.head

        self.head=new_node



    def delete(self,value):

        current=self.head

        previous=None


        while current:


            if current.value==value:


                if previous:

                    previous.next=current.next

                else:

                    self.head=current.next


                return


            previous=current

            current=current.next



    def traverse(self):

        result=[]

        current=self.head


        while current:

            result.append(
                current.value
            )

            current=current.next


        return result



