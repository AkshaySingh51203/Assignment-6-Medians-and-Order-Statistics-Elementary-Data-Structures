# -----------------------------
# Randomized Quickselect
# -----------------------------

def randomized_partition(arr, low, high):

    pivot_index = random.randint(low, high)

    arr[pivot_index], arr[high] = arr[high], arr[pivot_index]

    pivot = arr[high]

    i = low

    for j in range(low, high):

        if arr[j] <= pivot:

            arr[i], arr[j] = arr[j], arr[i]

            i += 1

    arr[i], arr[high] = arr[high], arr[i]

    return i



def randomized_quickselect(arr, low, high, k):

    if low == high:
        return arr[low]


    pivot = randomized_partition(
        arr,
        low,
        high
    )


    if k == pivot:

        return arr[k]

    elif k < pivot:

        return randomized_quickselect(
            arr,
            low,
            pivot-1,
            k
        )

    else:

        return randomized_quickselect(
            arr,
            pivot+1,
            high,
            k
        )



# -----------------------------
# Deterministic Median of Medians
# -----------------------------


def insertion_sort(arr):

    for i in range(1,len(arr)):

        key = arr[i]

        j = i-1

        while j >= 0 and arr[j] > key:

            arr[j+1] = arr[j]

            j -= 1

        arr[j+1] = key


    return arr



def find_median(arr):

    arr = insertion_sort(arr)

    return arr[len(arr)//2]



def median_of_medians(arr):

    if len(arr) <= 5:

        return find_median(arr)


    groups = []

    for i in range(0,len(arr),5):

        groups.append(arr[i:i+5])


    medians=[]

    for group in groups:

        medians.append(
            find_median(group)
        )


    return median_of_medians(medians)



def partition(arr,pivot):

    left=[]

    middle=[]

    right=[]


    for value in arr:

        if value < pivot:

            left.append(value)

        elif value == pivot:

            middle.append(value)

        else:

            right.append(value)


    return left,middle,right



def deterministic_select(arr,k):

    if len(arr)==1:

        return arr[0]


    pivot = median_of_medians(arr)


    left,middle,right = partition(
        arr,
        pivot
    )


    if k < len(left):

        return deterministic_select(
            left,
            k
        )


    elif k < len(left)+len(middle):

        return pivot


    else:

        return deterministic_select(
            right,
            k-len(left)-len(middle)
        )



